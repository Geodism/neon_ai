def _match_po_item_to_line(line: str, po_items: list):
    normalized_line = _normalize_text(line)
    if not normalized_line:
        return None

    best_item = None
    best_score = 0
    for item in po_items:
        description = item.get("Description") or ""
        normalized_desc = _normalize_text(description)
        if not normalized_desc:
            continue
        if normalized_desc in normalized_line:
            score = len(normalized_desc.split()) + 5
        else:
            desc_tokens = [tok for tok in normalized_desc.split() if len(tok) > 2]
            score = sum(1 for tok in desc_tokens if tok in normalized_line)
        if score > best_score:
            best_item = item
            best_score = score

    return best_item if best_score >= 2 else None


def parse_po_receipt_text(po_id: int, text: str, assume_received: bool = False):
    po_items = get_po_receipt_items(po_id)
    if not po_items:
        return {"received": [], "backordered": []}

    received = []
    backordered = []
    mode = "received" if assume_received else None

    for raw_line in (text or "").splitlines():
        line = raw_line.strip()
        lowered = line.lower()
        if not line:
            continue

        if any(marker in lowered for marker in ("received:", "arrived:", "picked up:", "on hand:")):
            mode = "received"
            continue
        if any(marker in lowered for marker in ("backordered:", "back ordered:", "remaining:", "short:")):
            mode = "backordered"
            continue

        item = _match_po_item_to_line(line, po_items)
        if not item:
            continue

        line_is_backordered = mode == "backordered" or ("backorder" in lowered or "back order" in lowered)
        line_is_received = mode == "received" or assume_received or any(
            token in lowered for token in ("received", "arrived", "picked up", "included", "shipped")
        )

        qty_values = _extract_numeric_values(line)
        remaining = float(item.get("Remaining") or 0)
        qty = qty_values[0] if qty_values else (remaining if line_is_received else 0)
        qty = max(0.0, min(float(qty), remaining))

        if line_is_backordered:
            backordered.append({"po_item_id": item["POItemID"], "description": item["Description"], "line": line})
        elif line_is_received and qty > 0:
            received.append((item["POItemID"], qty))

    deduped_received = {}
    for po_item_id, qty in received:
        deduped_received[po_item_id] = max(deduped_received.get(po_item_id, 0), qty)

    return {
        "received": [(po_item_id, qty) for po_item_id, qty in deduped_received.items()],
        "backordered": backordered,
    }


def update_purchase_order_receiving_status(po_id: int):
    ensure_purchase_schema()
    if po_is_fully_received(po_id):
        update_purchase_order_status(po_id, "FullyReceived")
        return "FullyReceived"

    conn = get_connection()
    cur = conn.cursor()
    try:
        cur.execute('''
            SELECT 1
            FROM "PurchaseOrderItem"
            WHERE "PurchaseOrderID" = %s
              AND COALESCE("QuantityReceived", 0) > 0
            LIMIT 1
        ''', (po_id,))
        has_received = cur.fetchone() is not None
    finally:
        conn.close()

    if has_received:
        update_purchase_order_status(po_id, "BackOrdered")
        return "BackOrdered"
    return get_purchase_order_status(po_id)


def get_po_followup_status(po_id: int):
    started_at = time.perf_counter()
    try:
        po_data = get_po_export_data(po_id)
        record = next((row for row in load_po_dispatch_log() if row.get("po_id") == po_id), {})
        eta_date_value = po_data.get("ExpectedArrivalDate") if po_data else None
        eta_note_value = po_data.get("ExpectedArrivalNote") if po_data else None
        status = {
            "po_status": po_data.get("Status") if po_data else None,
            "eta_text": eta_note_value or record.get("eta_text"),
            "eta_date": (eta_date_value.isoformat() if hasattr(eta_date_value, "isoformat") else eta_date_value) or record.get("eta_date"),
            "weekly_followup_active": bool(record.get("long_lead")) and not po_has_any_packing_slip(po_id) and not po_is_fully_received(po_id) and (po_data.get("Status") != "ReadyForPickup" if po_data else True),
            "next_followup": None,
            "sent_at": record.get("sent_at"),
            "ready_for_pickup_at": record.get("ready_for_pickup_at"),
            "last_weekly_followup_sent_at": record.get("last_weekly_followup_sent_at"),
            "eta_followup_sent_at": record.get("eta_followup_sent_at"),
            "recipient_email": record.get("recipient_email"),
        }

        if po_has_any_packing_slip(po_id) or po_is_fully_received(po_id):
            status["next_followup"] = "None - receipt logged"
            status["weekly_followup_active"] = False
            return status

        if record.get("ready_for_pickup_at"):
            status["next_followup"] = "Owner pickup pending"
            status["weekly_followup_active"] = False
            return status

        eta_date_raw = record.get("eta_date")
        if eta_date_raw:
            try:
                eta_date = datetime.date.fromisoformat(eta_date_raw)
                status["next_followup"] = str(eta_date + datetime.timedelta(days=1))
            except ValueError:
                pass

        if status["weekly_followup_active"]:
            last_weekly = record.get("last_weekly_followup_sent_at")
            if last_weekly:
                try:
                    next_weekly = datetime.datetime.fromisoformat(last_weekly).date() + datetime.timedelta(days=7)
                    status["next_followup"] = str(next_weekly)
                except ValueError:
                    pass
            elif record.get("sent_at"):
                try:
                    next_weekly = datetime.datetime.fromisoformat(record["sent_at"]).date() + datetime.timedelta(days=7)
                    status["next_followup"] = str(next_weekly)
                except ValueError:
                    pass

        return status
    finally:
        _perf_log("db", "purchases.get_po_followup_status", started_at)


def get_backordered_purchase_orders():
    ensure_purchase_schema()
    conn = get_connection()
    cur = conn.cursor(cursor_factory=RealDictCursor)
    try:
        cur.execute('''
            SELECT
                po."PurchaseOrderID",
                po."Date",
                po."Status",
                po."ExpectedArrivalDate",
                v."VendorName",
                s."SiteName",
                COUNT(*) FILTER (
                    WHERE COALESCE(poi."QuantityReceived", 0) < COALESCE(poi."QuantityOrdered", 0)
                ) AS "BackorderedLineCount"
            FROM "PurchaseOrder" po
            JOIN "Vendor" v ON po."VendorID" = v."VendorID"
            LEFT JOIN "WorkOrder" wo ON po."WorkOrderID" = wo."WorkOrderID"
            LEFT JOIN "Site" s ON wo."SiteID" = s."SiteID"
            JOIN "PurchaseOrderItem" poi ON poi."PurchaseOrderID" = po."PurchaseOrderID"
            WHERE po."Date" >= %s
            GROUP BY po."PurchaseOrderID", po."Date", po."Status", po."ExpectedArrivalDate", v."VendorName", s."SiteName"
            HAVING COUNT(*) FILTER (
                WHERE COALESCE(poi."QuantityReceived", 0) < COALESCE(poi."QuantityOrdered", 0)
            ) > 0
               AND COALESCE(SUM(COALESCE(poi."QuantityReceived", 0)), 0) > 0
            ORDER BY po."Date" ASC, po."PurchaseOrderID" ASC
        ''', (AUTOMATION_MIN_DATE,))
        return cur.fetchall()
    finally:
        conn.close()


