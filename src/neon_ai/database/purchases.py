    state = get_work_order_procurement_state(work_order_id)
    if not state:
        raise ValueError(
            "Cannot create this purchase order because no matching work order exists. "
            "Solution: create the work order from the approved estimate first, then order materials."
        )

    status_text = str(state.get("JobStatus") or "").strip()
    is_open = status_text.upper() == "OPEN" and not bool(state.get("IsClosed"))
    if is_open:
        return state

    raise ValueError(
        f"Cannot create this purchase order because Work Order #{work_order_id} is not open "
        f"(current status: {status_text or 'Unknown'}). Solution: reopen the work order or create a new open work order before ordering materials."
    )


