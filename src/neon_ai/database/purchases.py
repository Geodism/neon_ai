def _insert_purchase_order_items(cur, po_id: int, items: list, commit_estimate_lines: bool):
    inserted_po_item_ids = []
    for item in items:
        estimate_material_id = item.get('estimate_material_id')
        if estimate_material_id in (None, ""):
            estimate_material_id = item.get('mat_id')
        catalog_item_id = item.get('catalog_item_id')
        if catalog_item_id in (None, ""):
            catalog_item_id = item.get('item_id')
        qty = float(item.get('qty') or 0)
        price = float(item.get('price') or 0)
        desc = item.get('desc') or item.get('description')
        cur.execute('''
            INSERT INTO "PurchaseOrderItem" 
            ("PurchaseOrderID", "MaterialID", "CatalogItemID", "QuantityOrdered", "UnitPriceAtOrder", "LineTotal", "Description")
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            RETURNING "POItemID"
        ''', (
            po_id,
            estimate_material_id,
            catalog_item_id,
            qty,
            price,
            qty * price,
            desc,
        ))
        inserted_po_item_ids.append(int(cur.fetchone()["POItemID"]))

        if commit_estimate_lines and estimate_material_id:
            cur.execute('''
                UPDATE "EstimateMaterial" 
                SET "IsCommitted" = TRUE,
                    "CommittedUnitCost" = %s,
                    "CommittedLineTotal" = %s,
                    "IsOrdered" = CASE 
                        WHEN ("Quantity" <= (
                            SELECT SUM("QuantityOrdered") 
                            FROM "PurchaseOrderItem" 
                            WHERE "MaterialID" = %s
                        )) THEN TRUE ELSE FALSE END
                WHERE "EstimateMaterialID" = %s
            ''', (price, qty * price, estimate_material_id, estimate_material_id))
    return inserted_po_item_ids


def _save_purchase_order_record(
    work_order_id: int,
    items: list,
    vendor_id: int = None,
    status: str = "Locked",
    expected_date=None,
    expected_note: str = None,
    po_id: int = None,
):
    ensure_purchase_schema()
    validate_work_order_for_purchase_order(work_order_id)
    from neon_ai.database.connection import get_connection
    conn = get_connection()
    cur = conn.cursor(cursor_factory=RealDictCursor)
    try:
        total_val = sum(float(item.get('qty') or 0) * float(item.get('price') or 0) for item in items)
        status_text = str(status or "Draft").strip() or "Draft"
        commit_estimate_lines = status_text != "Draft"

        if po_id:
            cur.execute(
                '''
                SELECT "PurchaseOrderID", COALESCE("Status", '') AS "Status"
                FROM "PurchaseOrder"
                WHERE "PurchaseOrderID" = %s
                ''',
                (po_id,),
            )
            existing = cur.fetchone()
            if not existing:
                raise ValueError(f"Purchase Order #{po_id} was not found.")
            existing_status = str(existing.get("Status") or "").strip()
            if existing_status and existing_status not in {"Draft", "Locked"}:
                raise ValueError(f"Purchase Order #{po_id} is already {existing_status} and can no longer be rewritten from this workspace.")

            cur.execute(
                '''
                UPDATE "PurchaseOrder"
                SET "WorkOrderID" = %s,
                    "VendorID" = %s,
                    "Status" = %s,
                    "PurchaseOrderTotal" = %s,
                    "ExpectedArrivalDate" = %s,
                    "ExpectedArrivalNote" = %s,
                    "ShippingDocuments" = NULL
                WHERE "PurchaseOrderID" = %s
                ''',
                (work_order_id, vendor_id, status_text, total_val, expected_date or None, expected_note or None, po_id),
            )
            cur.execute('DELETE FROM "PurchaseOrderItem" WHERE "PurchaseOrderID" = %s', (po_id,))
            target_po_id = int(po_id)
        else:
            cur.execute('''
                INSERT INTO "PurchaseOrder" 
                ("WorkOrderID", "VendorID", "Date", "Status", "PurchaseOrderTotal", "ExpectedArrivalDate", "ExpectedArrivalNote")
                VALUES (%s, %s, CURRENT_DATE, %s, %s, %s, %s)
                RETURNING "PurchaseOrderID"
            ''', (work_order_id, vendor_id, status_text, total_val, expected_date or None, expected_note or None))
            target_po_id = int(cur.fetchone()["PurchaseOrderID"])

        if po_id:
            cur.execute('DELETE FROM "PurchaseOrderItemSourceLink" WHERE "PurchaseOrderID" = %s', (target_po_id,))
        inserted_po_item_ids = _insert_purchase_order_items(cur, target_po_id, items, commit_estimate_lines=commit_estimate_lines)
        for po_item_id, item in zip(inserted_po_item_ids, items):
            source_selection_id = item.get("rfq_carried_selection_id")
            source_price_request_id = item.get("source_price_request_id") or item.get("rfq_id")
            source_pr_item_id = item.get("source_pr_item_id")
            source_vendor_id = item.get("source_vendor_id") or item.get("vendor_id")
            source_estimate_id = item.get("source_estimate_id") or item.get("estimate_id")
            source_material_id = item.get("estimate_material_id") or item.get("mat_id")
            if all(
                value in (None, "", 0, "0")
                for value in (
                    source_selection_id,
                    source_price_request_id,
                    source_pr_item_id,
                    source_vendor_id,
                    source_estimate_id,
                    source_material_id,
                )
            ):
                continue
            cur.execute(
                '''
                INSERT INTO "PurchaseOrderItemSourceLink" (
                    "POItemID",
                    "PurchaseOrderID",
                    "RFQCarriedSelectionID",
                    "PriceRequestID",
                    "PRItemID",
                    "VendorID",
                    "EstimateID",
                    "MaterialID"
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                ''',
                (
                    po_item_id,
                    target_po_id,
                    source_selection_id or None,
                    source_price_request_id or None,
                    source_pr_item_id or None,
                    source_vendor_id or None,
                    source_estimate_id or None,
                    source_material_id or None,
                ),
            )
        conn.commit()
        return target_po_id
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

