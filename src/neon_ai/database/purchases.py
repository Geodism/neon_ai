def load_po_dispatch_log():
    if not os.path.exists(PO_DISPATCH_LOG_PATH):
        return []
    try:
        with open(PO_DISPATCH_LOG_PATH, "r", encoding="utf-8") as handle:
            data = json.load(handle)
        return data if isinstance(data, list) else []
    except Exception:
        return []


def save_po_dispatch_log(entries):
    with open(PO_DISPATCH_LOG_PATH, "w", encoding="utf-8") as handle:
        json.dump(entries, handle, indent=2)


def upsert_po_dispatch_record(po_id: int, updates: dict):
    entries = load_po_dispatch_log()
    for entry in entries:
        if entry.get("po_id") == po_id:
            entry.update(updates)
            save_po_dispatch_log(entries)
            return entry

    new_entry = {"po_id": po_id}
    new_entry.update(updates)
    entries.append(new_entry)
    save_po_dispatch_log(entries)
    return new_entry

