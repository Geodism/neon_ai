def log_material_receipt_batch(packing_slip: str, receive_date: str, items_arriving: list):
    """
    Takes a list of items and saves them all in one massive transaction.
    items_arriving format: [(po_item_id, quantity_arrived_today), ...]
    """
    ensure_purchase_schema()
    from neon_ai.database.connection import get_connection
    conn = get_connection()
    cur = conn.cursor()
    try:
        po_ids = set()
        receipt_ids_by_po = {}
        # Loop through the shopping cart and update everything!
        for item_id, qty_arrived in items_arriving:
            cur.execute('SELECT "PurchaseOrderID" FROM "PurchaseOrderItem" WHERE "POItemID" = %s', (item_id,))
            row = cur.fetchone()
            if row and row.get("PurchaseOrderID"):
                po_id = row["PurchaseOrderID"]
                po_ids.add(po_id)
                if po_id not in receipt_ids_by_po:
                    receipt_ids_by_po[po_id] = _get_or_create_purchase_order_receipt(
                        cur,
                        po_id=po_id,
                        document_ref=packing_slip,
                        receive_date=receive_date,
                        document_type="Packing Slip",
                    )
            cur.execute('''
                UPDATE "PurchaseOrderItem"
                SET "QuantityReceived" = COALESCE("QuantityReceived", 0) + %s,
                    "LastReceivedDate" = %s,
                    "LastPackingSlip" = %s
                WHERE "POItemID" = %s
            ''', (qty_arrived, receive_date, packing_slip, item_id))

            if row and row.get("PurchaseOrderID"):
                receipt_id = receipt_ids_by_po[row["PurchaseOrderID"]]
                cur.execute(
                    '''
                    SELECT "ReceiptItemID", COALESCE("QuantityReceived", 0) AS "QuantityReceived"
                    FROM public."PurchaseOrderReceiptItem"
                    WHERE "ReceiptID" = %s AND "POItemID" = %s
                    LIMIT 1
                    ''',
                    (receipt_id, item_id),
                )
                receipt_item = cur.fetchone()
                if receipt_item and receipt_item.get("ReceiptItemID"):
                    cur.execute(
                        '''
                        UPDATE public."PurchaseOrderReceiptItem"
                        SET "QuantityReceived" = COALESCE("QuantityReceived", 0) + %s
                        WHERE "ReceiptItemID" = %s
                        ''',
                        (qty_arrived, receipt_item["ReceiptItemID"]),
                    )
                else:
                    cur.execute(
                        '''
                        INSERT INTO public."PurchaseOrderReceiptItem"
                        ("ReceiptID", "POItemID", "QuantityReceived")
                        VALUES (%s, %s, %s)
                        ''',
                        (receipt_id, item_id, qty_arrived),
                    )
        
        # Only commit if EVERY item succeeded
        conn.commit()
        for po_id in po_ids:
            update_purchase_order_receiving_status(po_id)
        return True
    except Exception as e:
        # If even one item fails, roll the whole thing back to protect the database!
        conn.rollback()
        raise e
    finally:
        conn.close()
