def process_inbound_vendor_po_email(po_id: int, sender_email: str, subject: str, body: str, attachment_path: str = None, received_at=None):
    """Processes ETA updates, ready-for-pickup notices, and receipt updates tied to a PO."""
    from neon_ai.database.automation import log_estimate_action
    from neon_ai.database.rfq import extract_text_from_attachment, ocr_pdf_attachment
    from neon_ai.gateway import send_to_user

    po_data = get_po_export_data(po_id)
    if not po_data:
        return None

    attachment_text = ""
    if attachment_path and os.path.exists(attachment_path):
        attachment_text = extract_text_from_attachment(attachment_path)
        if not attachment_text and attachment_path.lower().endswith(".pdf"):
            attachment_text = ocr_pdf_attachment(attachment_path)

    combined_text = "\n".join(part for part in [subject, body, attachment_text] if part)
    lowered = combined_text.lower()
    eta_text = extract_eta_text(subject, combined_text)
    reference_date = received_at.date() if hasattr(received_at, "date") else datetime.date.today()
    eta_date = parse_eta_date(eta_text, reference_date=reference_date)
    ready_for_pickup = any(
        phrase in lowered for phrase in (
            "ready for pickup",
            "ready to pick up",
            "available for pickup",
            "will call",
            "order is ready",
            "parts are ready",
        )
    )
    receipt_email = bool(attachment_path) or any(
        phrase in lowered for phrase in (
            "packing slip",
            "received",
            "backordered",
            "back ordered",
            "picked up",
        )
    )

    existing_record = next((row for row in load_po_dispatch_log() if row.get("po_id") == po_id), {})

    updates = {
        "last_vendor_reply_at": (received_at.isoformat() if hasattr(received_at, "isoformat") else datetime.datetime.now().isoformat()),
        "last_vendor_reply_subject": (subject or "")[:255],
    }
    if eta_text:
        updates["eta_text"] = eta_text
    if eta_date:
        updates["eta_date"] = eta_date.isoformat()
        updates["long_lead"] = is_long_lead_eta(eta_date, existing_record.get("sent_at"))
        updates["eta_followup_sent_at"] = None
        updates["last_weekly_followup_sent_at"] = None
    if ready_for_pickup:
        updates["ready_for_pickup_at"] = updates["last_vendor_reply_at"]
    receipt_result = None
    if receipt_email:
        receipt_result = parse_po_receipt_text(
            po_id,
            combined_text,
            assume_received=bool(attachment_path) or "packing slip" in lowered
        )
    if eta_text or eta_date:
        set_purchase_order_expected_arrival(po_id, eta_date.isoformat() if eta_date else None, eta_text)
    upsert_po_dispatch_record(po_id, updates)

    estimate_id = po_data.get("EstimateID")
    if ready_for_pickup and po_data.get("Date") and po_data["Date"] >= AUTOMATION_MIN_DATE:
        update_purchase_order_status(po_id, "ReadyForPickup")
        if not existing_record.get("ready_pickup_notified_at"):
            send_to_user(
                subject=f"Parts Ready For Pickup: PO #{po_id}",
                content=(
                    f"{po_data.get('VendorName')} says the parts for PO #{po_id} are ready for pickup.\n\n"
                    f"Site: {po_data.get('SiteName')}\n"
                    f"Vendor message: {eta_text or subject or 'See inbox thread.'}\n\n"
                    "Next action: pick up the parts and send the packing slip or receipt details back to the Argon inbox."
                )
            )
            upsert_po_dispatch_record(po_id, {"ready_pickup_notified_at": datetime.datetime.now().isoformat()})
        if estimate_id:
            log_estimate_action(
                estimate_id,
                f"Vendor marked PO #{po_id} ready for pickup. Owner notified to collect parts.",
                "Purchase Order"
            )

    if receipt_result and receipt_result["received"]:
        packing_slip = infer_packing_slip_number(subject, body, attachment_path)
        receive_date = reference_date.isoformat()
        log_material_receipt_batch(packing_slip, receive_date, receipt_result["received"])
        new_status = update_purchase_order_receiving_status(po_id)
        update_payload = {
            "last_receipt_at": datetime.datetime.now().isoformat(),
            "last_packing_slip": packing_slip,
        }
        if new_status == "FullyReceived":
            update_payload["long_lead"] = False
        upsert_po_dispatch_record(po_id, update_payload)
        if estimate_id:
            log_estimate_action(
                estimate_id,
                f"Email-driven receipt logged for PO #{po_id}. Packing slip {packing_slip}. Received lines: {len(receipt_result['received'])}. Status -> {new_status}.",
                "Purchase Order"
            )
        if receipt_result["backordered"] and estimate_id:
            backordered_text = "; ".join(item["description"] for item in receipt_result["backordered"][:5])
            log_estimate_action(
                estimate_id,
                f"PO #{po_id} still has backordered items after receipt: {backordered_text}",
                "Purchase Order"
            )
    elif receipt_result and receipt_result["backordered"] and estimate_id:
        backordered_text = "; ".join(item["description"] for item in receipt_result["backordered"][:5])
        log_estimate_action(
            estimate_id,
            f"PO #{po_id} email mentioned outstanding or backordered items, but no received quantities were parsed yet. The PO status was left unchanged until an initial delivery is logged. Outstanding lines: {backordered_text}",
            "Purchase Order"
        )

    if estimate_id:
        if eta_date:
            log_estimate_action(
                estimate_id,
                f"Vendor ETA received for PO #{po_id} from {sender_email}. ETA: {eta_date.isoformat()}. Detail: {eta_text or 'Not captured.'}",
                "Purchase Order"
            )
        else:
            log_estimate_action(
                estimate_id,
                f"Vendor replied to PO #{po_id} from {sender_email}, but no parseable ETA was found. Detail: {eta_text or 'No ETA sentence detected.'}",
                "Purchase Order"
            )

    return {
        "po_id": po_id,
        "estimate_id": estimate_id,
        "vendor_name": po_data.get("VendorName"),
        "site_name": po_data.get("SiteName"),
        "eta_text": eta_text,
        "eta_date": eta_date.isoformat() if eta_date else None,
        "long_lead": is_long_lead_eta(eta_date, existing_record.get("sent_at")) if eta_date else False,
        "ready_for_pickup": ready_for_pickup,
        "receipt_logged": bool(receipt_result and receipt_result["received"]),
        "received_count": len(receipt_result["received"]) if receipt_result else 0,
        "backordered_count": len(receipt_result["backordered"]) if receipt_result else 0,
    }


