def split_receipt_refs(raw_refs: str):
    parts = []
    for chunk in str(raw_refs or "").split("|"):
        ref = chunk.strip()
        if ref and ref not in parts:
            parts.append(ref)
    return parts


def _get_or_create_purchase_order_receipt(cur, po_id: int, document_ref: str, receive_date: str, document_type: str = "Packing Slip"):
    cur.execute(
        '''
        SELECT "ReceiptID"
        FROM public."PurchaseOrderReceipt"
        WHERE "PurchaseOrderID" = %s
          AND LOWER(TRIM(COALESCE("DocumentRef", ''))) = LOWER(TRIM(COALESCE(%s, '')))
        ORDER BY "ReceiptID" DESC
        LIMIT 1
        ''',
        (po_id, document_ref),
    )
    existing = cur.fetchone()
    if existing and existing.get("ReceiptID"):
        cur.execute(
            '''
            UPDATE public."PurchaseOrderReceipt"
            SET "ReceiveDate" = COALESCE(%s, "ReceiveDate"),
                "DocumentType" = COALESCE(%s, "DocumentType")
            WHERE "ReceiptID" = %s
            ''',
            (receive_date or None, document_type or None, existing["ReceiptID"]),
        )
        return int(existing["ReceiptID"])

    cur.execute(
        '''
        INSERT INTO public."PurchaseOrderReceipt"
        ("PurchaseOrderID", "DocumentType", "DocumentRef", "ReceiveDate")
        VALUES (%s, %s, %s, %s)
        RETURNING "ReceiptID"
        ''',
        (po_id, document_type or "Packing Slip", document_ref, receive_date or None),
    )
    row = cur.fetchone()
    return int(row["ReceiptID"])


def get_purchase_order_receipt_choices(po_id: int):
    ensure_purchase_schema()
    conn = get_connection()
    cur = conn.cursor(cursor_factory=RealDictCursor)
    try:
        cur.execute(
            '''
            SELECT
                pr."ReceiptID",
                COALESCE(pr."DocumentType", 'Packing Slip') AS "DocumentType",
                COALESCE(pr."DocumentRef", '') AS "DocumentRef",
                pr."ReceiveDate",
                COUNT(pri."ReceiptItemID") AS "LineCount",
                COALESCE(SUM(pri."QuantityReceived"), 0) AS "TotalQty"
            FROM public."PurchaseOrderReceipt" pr
            LEFT JOIN public."PurchaseOrderReceiptItem" pri ON pri."ReceiptID" = pr."ReceiptID"
            WHERE pr."PurchaseOrderID" = %s
            GROUP BY pr."ReceiptID", pr."DocumentType", pr."DocumentRef", pr."ReceiveDate"
            ORDER BY COALESCE(pr."ReceiveDate"::text, '') DESC, pr."ReceiptID" DESC
            ''',
            (po_id,),
        )
        db_rows = cur.fetchall()

        cur.execute(
            '''
            SELECT DISTINCT COALESCE("LastPackingSlip", '') AS "DocumentRef"
            FROM "PurchaseOrderItem"
            WHERE "PurchaseOrderID" = %s
              AND COALESCE("LastPackingSlip", '') != ''
            ''',
            (po_id,),
        )
        legacy_rows = cur.fetchall()
    finally:
        conn.close()

    choices = []
    seen_refs = set()
    for row in db_rows:
        ref = str(row.get("DocumentRef") or "").strip()
        if ref:
            seen_refs.add(ref.lower())
        receive_date = row.get("ReceiveDate")
        date_text = receive_date.isoformat() if hasattr(receive_date, "isoformat") else (receive_date or "Unknown Date")
        choices.append(
            {
                "Key": f"receipt:{int(row['ReceiptID'])}",
                "ReceiptID": int(row["ReceiptID"]),
                "DocumentRef": ref,
                "DocumentType": row.get("DocumentType") or "Packing Slip",
                "ReceiveDate": date_text,
                "Source": "ledger",
                "Label": f"{row.get('DocumentType') or 'Packing Slip'} {ref or '(no ref)'} | {date_text} | {int(float(row.get('LineCount') or 0))} line(s)",
            }
        )

    for row in legacy_rows:
        for ref in split_receipt_refs(row.get("DocumentRef")):
            if ref.lower() in seen_refs:
                continue
            seen_refs.add(ref.lower())
            choices.append(
                {
                    "Key": f"legacy:{ref}",
                    "ReceiptID": None,
                    "DocumentRef": ref,
                    "DocumentType": "Legacy Receipt",
                    "ReceiveDate": "",
                    "Source": "legacy",
                    "Label": f"Legacy receipt {ref}",
                }
            )

    choices.append(
        {
            "Key": "all_received",
            "ReceiptID": None,
            "DocumentRef": "All received material",
            "DocumentType": "All Received",
            "ReceiveDate": "",
            "Source": "aggregate",
            "Label": "All received material on this PO",
        }
    )
    return choices


