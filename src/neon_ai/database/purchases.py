def extract_po_id_from_text(subject="", body=""):
    text = f"{subject or ''}\n{body or ''}"
    match = re.search(r'\bpo\s*#?\s*(\d+)\b', text, re.IGNORECASE)
    return int(match.group(1)) if match else None


def find_matching_po_for_email(sender_email, subject="", body=""):
    po_id = extract_po_id_from_text(subject, body)
    if po_id:
        return po_id

    combined = f"{subject or ''}\n{body or ''}".lower()
    po_keywords = ("purchase order", " po ", "eta", "lead time", "ship", "shipment", "backorder")
    if not any(keyword in combined for keyword in po_keywords):
        return None

    sender = (sender_email or "").strip().lower()
    if not sender:
        return None

    matches = [
        row for row in load_po_dispatch_log()
        if (row.get("recipient_email") or "").strip().lower() == sender
    ]
    if not matches:
        return None
    matches.sort(key=lambda row: row.get("sent_at", ""), reverse=True)
    return matches[0].get("po_id")


def extract_eta_text(subject="", body_text=""):
    combined = f"{subject or ''}\n{body_text or ''}"
    sentences = re.split(r'(?<=[.!?])\s+|\n+', combined)
    best_sentence = None
    best_score = 0
    for sentence in sentences:
        lowered = sentence.lower().strip()
        if not lowered:
            continue

        score = 0
        if re.search(r'\beta\b', lowered):
            score += 5
        if re.search(r'\barriv|\blead time\b', lowered):
            score += 4
        if re.search(r'\bship|\bdelivery\b', lowered):
            score += 2
        if re.search(r'\bnext week\b|\btomorrow\b|\bthis week\b|\bby\s+[A-Za-z]+\b|\bin\s+\d+\s+(day|days|week|weeks)\b|\b\d+\s*(business )?(day|days|week|weeks)\b', lowered):
            score += 4
        if re.search(r'\b20\d{2}-\d{1,2}-\d{1,2}\b', sentence):
            score += 6
        if re.search(r'\b(january|february|march|april|may|june|july|august|september|october|november|december)\s+\d{1,2}\b', lowered):
            score += 5
        if score > best_score:
            best_sentence = sentence.strip()[:255]
            best_score = score
    if best_score > 0:
        return best_sentence
    return None


def parse_eta_date(eta_text: str, reference_date=None):
    if not eta_text:
        return None

    reference_date = reference_date or datetime.date.today()
    lowered = eta_text.lower()

    iso_match = re.search(r'\b(20\d{2})-(\d{1,2})-(\d{1,2})\b', eta_text)
    if iso_match:
        year, month, day = map(int, iso_match.groups())
        return datetime.date(year, month, day)

    md_match = re.search(r'\b(january|february|march|april|may|june|july|august|september|october|november|december)\s+(\d{1,2})(?:st|nd|rd|th)?\b', lowered)
    if md_match:
        month_name, day_value = md_match.groups()
        month = datetime.datetime.strptime(month_name.title(), "%B").month
        year = reference_date.year
        parsed = datetime.date(year, month, int(day_value))
        if parsed < reference_date:
            parsed = datetime.date(year + 1, month, int(day_value))
        return parsed

    if "tomorrow" in lowered:
        return reference_date + datetime.timedelta(days=1)
    if "next week" in lowered:
        return reference_date + datetime.timedelta(days=7)
    if "this week" in lowered:
        return reference_date + datetime.timedelta(days=3)

    in_match = re.search(r'\bin\s+(\d+)\s+(day|days|week|weeks)\b', lowered)
    if in_match:
        qty = int(in_match.group(1))
        unit = in_match.group(2)
        return reference_date + datetime.timedelta(days=qty * (7 if "week" in unit else 1))

    qty_match = re.search(r'\b(\d+)\s*(business\s+)?(day|days|week|weeks)\b', lowered)
    if qty_match:
        qty = int(qty_match.group(1))
        unit = qty_match.group(3)
        days = qty * (7 if "week" in unit else 1)
        return reference_date + datetime.timedelta(days=days)

    weekdays = {
        "monday": 0,
        "tuesday": 1,
        "wednesday": 2,
        "thursday": 3,
        "friday": 4,
        "saturday": 5,
        "sunday": 6,
    }
    for name, index in weekdays.items():
        if re.search(rf'\b{name}\b', lowered):
            delta = (index - reference_date.weekday()) % 7
            delta = 7 if delta == 0 else delta
            return reference_date + datetime.timedelta(days=delta)

    return None


def is_long_lead_eta(eta_date, sent_at=None):
    if not eta_date:
        return False
    if isinstance(sent_at, str):
        try:
            sent_at = datetime.datetime.fromisoformat(sent_at)
        except ValueError:
            sent_at = None
    sent_date = sent_at.date() if isinstance(sent_at, datetime.datetime) else datetime.date.today()
    return (eta_date - sent_date).days > 7


