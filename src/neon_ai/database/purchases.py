        if not po_data:
            continue
        if po_data.get("Status") == "ReadyForPickup":
            continue

        eta_date_raw = record.get("eta_date")
        eta_date = None
        if eta_date_raw:
            try:
                eta_date = datetime.date.fromisoformat(eta_date_raw)
            except ValueError:
                eta_date = None

        recipient_email = record.get("recipient_email") or get_vendor_email_for_po(po_id)
        estimate_id = po_data.get("EstimateID")

        if eta_date and today >= eta_date + datetime.timedelta(days=1):
            if not record.get("eta_followup_sent_at"):
                send_to_user(
                    subject=f"Packing Slip Follow-Up Needed: PO #{po_id}",
                    content=(
                        f"PO #{po_id} for {po_data.get('VendorName')} has reached the promised ETA window and no packing slip has been logged yet.\n\n"
                        f"Site: {po_data.get('SiteName')}\n"
                        f"ETA provided: {eta_date.isoformat()}\n"
                        f"Vendor ETA note: {record.get('eta_text') or 'None captured'}\n\n"
                        "Please follow up with the wholesaler."
                    )
                )
                record["eta_followup_sent_at"] = datetime.datetime.now().isoformat()
                if estimate_id:
                    log_estimate_action(
                        estimate_id,
                        f"24-hour post-ETA owner reminder sent for PO #{po_id}; no packing slip logged after ETA {eta_date.isoformat()}.",
                        "Purchase Order"
                    )

        if record.get("long_lead") and recipient_email:
            last_weekly_raw = record.get("last_weekly_followup_sent_at")
            last_weekly = None
            if last_weekly_raw:
                try:
                    last_weekly = datetime.datetime.fromisoformat(last_weekly_raw)
                except ValueError:
                    last_weekly = None

            if last_weekly is None or today >= last_weekly.date() + datetime.timedelta(days=7):
                if not _background_vendor_po_followups_enabled():
                    print(
                        "PO Sweeper: Background vendor follow-up is disabled. "
                        "Use manual PO follow-up/send workflow. "
                        f"PO #{po_id} for {po_data.get('VendorName')} needs manual weekly follow-up."
                    )
                else:
                    sent = send_to_user(
                        subject=f"Weekly Check-In: PO #{po_id}",
                        content=(
                            f"Hello {po_data.get('VendorName')},\n\n"
                            f"We are checking in on Purchase Order #{po_id} for {po_data.get('SiteName')}.\n\n"
                            "Please confirm the parts remain on order and share any updated ETA or shipment details.\n\n"
                            "Thank you,\nArgon Electrical"
                        ),
                        recipient=recipient_email,
                        cc_recipients=[MY_EMAIL]
                    )
                    if sent:
                        record["last_weekly_followup_sent_at"] = datetime.datetime.now().isoformat()
                        if estimate_id:
                            log_estimate_action(
                                estimate_id,
                                f"Weekly long-lead vendor follow-up sent for PO #{po_id} to {po_data.get('VendorName')}.",
                                "Purchase Order"
                            )

        upsert_po_dispatch_record(po_id, record)

